import { writeFile } from "node:fs/promises";
import { URL } from "node:url";

const SOURCE = "https://cdn.jsdelivr.net/npm/quran-json@3.1.2/dist/chapters/en/18.json";
const response = await globalThis.fetch(SOURCE);
if (!response.ok) throw new Error(`Qur'an source failed: ${response.status}`);

const chapter = await response.json();
if (chapter.id !== 18 || chapter.total_verses !== 110 || chapter.verses.length !== 110) {
  throw new Error("Unexpected Surah Al-Kahf response");
}

const verses = chapter.verses.map(({ id, text, transliteration, translation }) => ({
  id,
  text,
  transliteration,
  translation,
}));

const output = `// Generated by scripts/generate-friday-kahf.mjs from quran-json 3.1.2.
// Arabic: Uthmani text from the Noble Qur'an Encyclopedia; English: Saheeh International.
import type { ZikrDraft } from "../types";

const VERSES = ${JSON.stringify(verses, null, 2)} as const;

const arabicNumber = (value: number) =>
  String(value).replace(/\\d/g, (digit) => "٠١٢٣٤٥٦٧٨٩"[Number(digit)]!);

export const FRIDAY_KAHF: ZikrDraft[] = [
  {
    id: "friday-kahf",
    category: "friday_kahf",
    orderIndex: 0,
    isSurah: true,
    surahNameArabic: "الكَهْف",
    surahNameEnglish: "Al-Kahf",
    surahType: "Meccan",
    verseCount: 110,
    hasBasmalah: true,
    arabicText: VERSES.map((verse) => \`\${verse.text} ﴿\${arabicNumber(verse.id)}﴾\`).join(" "),
    transliteration: VERSES.map((verse) => verse.transliteration).join(" "),
    translation: VERSES.map((verse, index) => \`\${verse.translation} (\${index + 1})\`).join(" "),
    benefit: "Recite Surah Al-Kahf on Friday.",
    benefitArabic: "تُقرأ سورة الكهف يوم الجمعة.",
    repetitionCount: 1,
    countLabel: "1",
    sourceReference: "Qur'an 18:1-110.",
    sourceReferenceArabic: "القرآن الكريم، سورة الكهف (١٨:١-١١٠).",
    preferredTiming: "Friday.",
  },
];
`;

await writeFile(new URL("../src/app/content/fridayKahf.ts", import.meta.url), output, "utf8");
