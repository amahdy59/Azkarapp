import { readFile, writeFile } from "node:fs/promises";

// Arabic is copied verbatim from the reviewed shipped Mushaf, not authored here.
// English/transliteration use the same editions as generate-quran-passages.mjs.
const numbers = Array.from({ length: 11 }, (_, index) => index + 190);
const pages = await Promise.all(
  [75, 76].map(async (page) => JSON.parse(await readFile(`public/data/mushaf/${page}.json`, "utf8"))),
);
const verses = pages
  .flat()
  .filter((verse) => numbers.includes(Number(verse.k.split(":")[1])) && verse.k.startsWith("3:"));
if (verses.map((verse) => verse.k).join() !== numbers.map((number) => `3:${number}`).join())
  throw new Error("Incomplete Al-Imran range");
const response = await globalThis.fetch(
  "https://api.alquran.cloud/v1/surah/3/editions/en.transliteration,en.pickthall",
  {
    signal: globalThis.AbortSignal.timeout(30000),
  },
);
if (!response.ok) throw new Error(`Al-Imran editions: HTTP ${response.status}`);
const { data } = await response.json();
const select = (edition) => {
  const selected = data
    .find((item) => item.edition.identifier === edition)
    ?.ayahs.filter((ayah) => numbers.includes(ayah.numberInSurah));
  if (selected?.map((ayah) => ayah.numberInSurah).join() !== numbers.join()) throw new Error(`Incomplete ${edition}`);
  return selected.map((ayah) => `${ayah.text} (${ayah.numberInSurah})`).join(" ");
};
const passage = {
  surahNameArabic: "آل عِمْرَان (١٩٠–٢٠٠)",
  surahNameEnglish: "Al-Imran (190–200)",
  verseCount: 11,
  arabicText: verses.map((verse) => verse.w.map((word) => (word[2] ? `﴿${word[3]}﴾` : word[3])).join(" ")).join(" "),
  transliteration: select("en.transliteration"),
  translation: select("en.pickthall"),
};
await writeFile(
  "src/app/content/quranImranPassage.ts",
  `// Generated by scripts/prepare-imran-passage.mjs.\n// Arabic: reviewed Mushaf pages 75–76. English: Pickthall.\nimport type { QuranPassage } from "./quranPassages";\n\nexport const QURAN_IMRAN_PASSAGE = ${JSON.stringify(passage, null, 2)} satisfies QuranPassage;\n`,
);

// Reuse the already shipped sourced glosses; never invent explanations.
const meanings = JSON.parse(await readFile("src/app/content/quranWordMeanings.data.json", "utf8"));
const chapter = JSON.parse(await readFile("public/data/word-meanings/3.json", "utf8"));
meanings["3"] = Object.fromEntries(Object.entries(chapter).filter(([ayah]) => numbers.includes(Number(ayah))));
await writeFile("src/app/content/quranWordMeanings.data.json", JSON.stringify(meanings, null, 2) + "\n");
