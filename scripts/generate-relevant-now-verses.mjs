import { writeFile } from "node:fs/promises";
import { format, resolveConfig } from "prettier";

/**
 * Generates the Qur'anic half of the "Relevant Now" source library.
 *
 * The rule this exists to keep: the app ships the Qur'an text it displays,
 * verified once and stored locally, with no runtime dependency on any Qur'an
 * service — and the Arabic is never hand-typed into a source file. This is the
 * same pipeline and the same editions as `generate-quran-passages.mjs`
 * (Uthmani Arabic, public-domain Pickthall English), narrowed to the specific
 * verses the contextual reminder draws on.
 *
 * Only the text is generated. Which contexts a verse belongs to, and the line
 * that introduces it, are editorial decisions and live in the content file that
 * imports this one — generated text and reviewed curation should not share a
 * file that a regeneration overwrites.
 *
 * Run: node scripts/generate-relevant-now-verses.mjs
 */
const editions = "quran-uthmani,en.pickthall";
const OUTPUT = "src/app/content/relevantNowVerses.ts";

/** The 18 Qur'an entries of the V1 library, in the order they were reviewed. */
const VERSES = [
  { id: "Q01", surah: 4, from: 103, to: 103, surahEnglish: "An-Nisa" },
  { id: "Q02", surah: 29, from: 45, to: 45, surahEnglish: "Al-Ankabut" },
  { id: "Q03", surah: 17, from: 78, to: 78, surahEnglish: "Al-Isra" },
  { id: "Q04", surah: 33, from: 41, to: 42, surahEnglish: "Al-Ahzab" },
  { id: "Q05", surah: 30, from: 17, to: 18, surahEnglish: "Ar-Rum" },
  { id: "Q06", surah: 2, from: 152, to: 152, surahEnglish: "Al-Baqarah" },
  { id: "Q07", surah: 13, from: 28, to: 28, surahEnglish: "Ar-Ra'd" },
  { id: "Q08", surah: 2, from: 238, to: 238, surahEnglish: "Al-Baqarah" },
  { id: "Q09", surah: 50, from: 39, to: 40, surahEnglish: "Qaf" },
  { id: "Q10", surah: 20, from: 130, to: 130, surahEnglish: "Ta-Ha" },
  { id: "Q11", surah: 11, from: 114, to: 114, surahEnglish: "Hud" },
  { id: "Q12", surah: 17, from: 79, to: 79, surahEnglish: "Al-Isra" },
  { id: "Q13", surah: 25, from: 64, to: 64, surahEnglish: "Al-Furqan" },
  { id: "Q14", surah: 73, from: 20, to: 20, surahEnglish: "Al-Muzzammil" },
  { id: "Q15", surah: 3, from: 190, to: 191, surahEnglish: "Al-Imran" },
  { id: "Q16", surah: 2, from: 255, to: 255, surahEnglish: "Al-Baqarah" },
  { id: "Q17", surah: 2, from: 285, to: 286, surahEnglish: "Al-Baqarah" },
  { id: "Q18", surah: 62, from: 9, to: 10, surahEnglish: "Al-Jumu'ah" },
];

const arabicNumber = (value) => String(value).replace(/\d/g, (digit) => "٠١٢٣٤٥٦٧٨٩"[Number(digit)]);
const quote = (value) => JSON.stringify(value);

async function fetchAyah(surah, ayah) {
  const response = await globalThis.fetch(`https://api.alquran.cloud/v1/ayah/${surah}:${ayah}/editions/${editions}`);
  if (!response.ok) throw new Error(`Qur'an API failed for ${surah}:${ayah}: ${response.status}`);
  const { data } = await response.json();
  const byEdition = Object.fromEntries(data.map((entry) => [entry.edition.identifier, entry]));
  return {
    arabic: byEdition["quran-uthmani"].text,
    english: byEdition["en.pickthall"].text,
    surahArabic: byEdition["quran-uthmani"].surah.name,
  };
}

const entries = [];
for (const verse of VERSES) {
  const numbers = [];
  for (let ayah = verse.from; ayah <= verse.to; ayah += 1) numbers.push(ayah);
  /* Sequential on purpose: this runs by hand, a handful of times ever, and a
     burst of parallel requests at a free public API is a poor trade for a few
     seconds. */
  const fetched = [];
  for (const ayah of numbers) fetched.push(await fetchAyah(verse.surah, ayah));

  const range = verse.from === verse.to ? `${verse.from}` : `${verse.from}-${verse.to}`;
  entries.push({
    id: verse.id,
    reference: `Qur'an ${verse.surah}:${range}`,
    referenceArabic: `القرآن ${arabicNumber(verse.surah)}:${arabicNumber(verse.from)}${
      verse.from === verse.to ? "" : `-${arabicNumber(verse.to)}`
    }`,
    surahEnglish: verse.surahEnglish,
    surahArabic: fetched[0].surahArabic,
    arabic: fetched.map((ayah, index) => `${ayah.arabic} ﴿${arabicNumber(numbers[index])}﴾`).join(" "),
    english: fetched.map((ayah) => ayah.english).join(" "),
  });
  console.log(`fetched ${verse.id} — ${verse.surah}:${range}`);
}

const body = entries
  .map(
    (entry) => `  {
    id: ${quote(entry.id)},
    reference: ${quote(entry.reference)},
    referenceArabic: ${quote(entry.referenceArabic)},
    surahEnglish: ${quote(entry.surahEnglish)},
    surahArabic: ${quote(entry.surahArabic)},
    arabic: ${quote(entry.arabic)},
    english: ${quote(entry.english)},
  },`,
  )
  .join("\n");

const source = `// Generated by scripts/generate-relevant-now-verses.mjs from api.alquran.cloud.
// Arabic: Uthmani text; English: public-domain Pickthall translation.
// Do not edit by hand — curation lives in relevantNowLibrary.ts.

export interface RelevantNowVerse {
  id: string;
  reference: string;
  referenceArabic: string;
  surahEnglish: string;
  surahArabic: string;
  arabic: string;
  english: string;
}

export const RELEVANT_NOW_VERSES: readonly RelevantNowVerse[] = [
${body}
];
`;

/* Formatted here rather than left for `pnpm format` afterwards. Generated
   output that is not Prettier-shaped fails the `format` stage of `pnpm check`
   and of the pre-push gate, so a generator that does not do this leaves a trap
   for whoever next regenerates the file. */
const options = (await resolveConfig(OUTPUT)) ?? {};
await writeFile(OUTPUT, await format(source, { ...options, parser: "typescript" }), "utf8");

console.log(`wrote ${entries.length} verses to ${OUTPUT}`);
