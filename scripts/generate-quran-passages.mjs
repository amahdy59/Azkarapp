import { writeFile } from "node:fs/promises";
import { URL } from "node:url";

const editions = "quran-uthmani,en.transliteration,en.pickthall";
const surahMetadata = {
  32: { key: "asSajdah", arabicName: "السَّجْدَة", englishName: "As-Sajdah", type: "Meccan" },
  67: { key: "alMulk", arabicName: "الْمُلْك", englishName: "Al-Mulk", type: "Meccan" },
  109: { key: "alKafirun", arabicName: "الْكَافِرُون", englishName: "Al-Kafirun", type: "Meccan" },
  112: { key: "alIkhlas", arabicName: "الْإِخْلَاص", englishName: "Al-Ikhlas", type: "Meccan" },
  113: { key: "alFalaq", arabicName: "الْفَلَق", englishName: "Al-Falaq", type: "Meccan" },
  114: { key: "anNas", arabicName: "النَّاس", englishName: "An-Nas", type: "Meccan" },
};

const arabicNumber = (value) => String(value).replace(/\d/g, (digit) => "٠١٢٣٤٥٦٧٨٩"[Number(digit)]);
const stripBasmalah = (text) => text.replace(/^بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ\s*/u, "");
const quote = (value) => JSON.stringify(value);

async function fetchSurah(number) {
  const response = await globalThis.fetch(`https://api.alquran.cloud/v1/surah/${number}/editions/${editions}`);
  if (!response.ok) throw new Error(`Qur'an API failed for surah ${number}: ${response.status}`);
  const { data } = await response.json();
  return Object.fromEntries(data.map((edition) => [edition.edition.identifier, edition.ayahs]));
}

const allSurahs = Object.fromEntries(
  await Promise.all(Object.keys(surahMetadata).map(async (number) => [number, await fetchSurah(number)])),
);
const alBaqarah = await fetchSurah(2);

function passageFromAyahs(metadata, editionsByName, selectedNumbers) {
  const select = (edition) =>
    editionsByName[edition].filter((ayah) => !selectedNumbers || selectedNumbers.includes(ayah.numberInSurah));
  const arabic = select("quran-uthmani");
  const transliteration = select("en.transliteration");
  const translation = select("en.pickthall");
  return {
    ...metadata,
    verseCount: arabic.length,
    arabicText: arabic
      .map(
        (ayah, index) =>
          `${index === 0 && metadata.hasBasmalah ? stripBasmalah(ayah.text) : ayah.text} ﴿${arabicNumber(ayah.numberInSurah)}﴾`,
      )
      .join(" "),
    transliteration:
      (metadata.hasBasmalah ? "Bismillāhir-Raḥmānir-Raḥīm. " : "") +
      transliteration.map((ayah) => `${ayah.text} (${ayah.numberInSurah})`).join(" "),
    translation:
      (metadata.hasBasmalah ? "In the name of Allah, the Beneficent, the Merciful. " : "") +
      translation.map((ayah) => `${ayah.text} (${ayah.numberInSurah})`).join(" "),
  };
}

const passages = Object.fromEntries(
  Object.entries(surahMetadata).map(([number, metadata]) => [
    metadata.key,
    passageFromAyahs(
      {
        surahNameArabic: metadata.arabicName,
        surahNameEnglish: metadata.englishName,
        surahType: metadata.type,
        hasBasmalah: true,
      },
      allSurahs[number],
    ),
  ]),
);

passages.ayatAlKursi = passageFromAyahs(
  {
    surahNameArabic: "الْبَقَرَة (آيَةُ الْكُرْسِيِّ)",
    surahNameEnglish: "Al-Baqarah (Ayat al-Kursi)",
    hasSeekRefuge: true,
  },
  alBaqarah,
  [255],
);
passages.lastTwoAlBaqarah = passageFromAyahs(
  {
    surahNameArabic: "الْبَقَرَة (٢٨٥–٢٨٦)",
    surahNameEnglish: "Al-Baqarah (285–286)",
    hasSeekRefuge: true,
  },
  alBaqarah,
  [285, 286],
);

const fields = [
  "surahNameArabic",
  "surahNameEnglish",
  "surahType",
  "verseCount",
  "hasBasmalah",
  "hasSeekRefuge",
  "arabicText",
  "transliteration",
  "translation",
];
const body = Object.entries(passages)
  .map(([key, passage]) => {
    const lines = fields
      .filter((field) => passage[field] !== undefined)
      .map((field) => `    ${field}: ${quote(passage[field])},`)
      .join("\n");
    return `  ${key}: {\n${lines}\n  },`;
  })
  .join("\n");

const output = `// Generated by scripts/generate-quran-passages.mjs from api.alquran.cloud.\n// Arabic: Uthmani text; English: public-domain Pickthall translation.\nimport type { Zikr } from "../types";\n\nexport type QuranPassage = Pick<\n  Zikr,\n  | "arabicText"\n  | "transliteration"\n  | "translation"\n  | "surahNameArabic"\n  | "surahNameEnglish"\n  | "surahType"\n  | "verseCount"\n  | "hasBasmalah"\n  | "hasSeekRefuge"\n>;\n\nexport const QURAN_PASSAGES = {\n${body}\n} as const satisfies Record<string, QuranPassage>;\n`;

await writeFile(new URL("../src/app/content/quranPassages.ts", import.meta.url), output, "utf8");
