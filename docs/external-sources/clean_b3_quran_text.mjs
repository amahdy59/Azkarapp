import fs from "node:fs";

const b3 = JSON.parse(fs.readFileSync("docs/external-sources/book3_al_wird_an_nabawi_pages.json", "utf8"));

function setPageLines(pageNum, newLines) {
  const p = b3.find((x) => x.page === pageNum);
  if (p) {
    p.lines = newLines;
    console.log(`Updated Page ${pageNum}`);
  } else {
    console.warn(`Page ${pageNum} not found!`);
  }
}

